#include <unistd.h>

void	ft_print_numbers(void)
{
	char	n;

	n = '0';
	int	i;
	i = 0;
	
	while (i <= 13)
	{
		write(1, &n, 1);
		n++;
		i++;
	}
}


int main()
{
	ft_print_numbers();
	return (0);

}
